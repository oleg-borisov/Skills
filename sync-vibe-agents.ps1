#requires -Version 7.0

[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

$repoRoot = $PSScriptRoot
$sourceRoot = Join-Path $repoRoot 'agents'
$outputRoot = Join-Path $repoRoot '.vibe\agents'
$agentNames = @('implementer', 'verifier', 'standards-reviewer', 'spec-reviewer', 'reviser', 'scout')
$readOnlyAgents = @('verifier', 'standards-reviewer', 'spec-reviewer')

# Контракт leaf-agents: вложенных запусков агентов быть не должно.
# agents_spawn — spawn-инструмент Vibe для subagents.
$disabledTools = @('agents_spawn')

# Лимит Vibe на instructions subagent-профиля.
$maxInstructionsLength = 65536

function ConvertTo-TomlString {
    param([Parameter(Mandatory)][string]$Value)

    return $Value.Replace('\', '\\').Replace('"', '\"')
}

if (-not (Test-Path -LiteralPath $outputRoot)) {
    New-Item -ItemType Directory -Path $outputRoot -Force | Out-Null
}

foreach ($agentName in $agentNames) {
    $sourcePath = Join-Path $sourceRoot "$agentName.md"
    if (-not (Test-Path -LiteralPath $sourcePath)) {
        throw "Отсутствует канонический агент: $sourcePath"
    }

    $raw = Get-Content -LiteralPath $sourcePath -Raw
    $documentMatch = [regex]::Match(
        $raw,
        '\A---\r?\n(?<frontmatter>.*?)\r?\n---\r?\n(?<body>.*)\z',
        [System.Text.RegularExpressions.RegexOptions]::Singleline)
    if (-not $documentMatch.Success) {
        throw "Некорректный frontmatter: $sourcePath"
    }

    $descriptionMatch = [regex]::Match($documentMatch.Groups['frontmatter'].Value, '(?m)^description:\s*(?<value>.+)$')
    if (-not $descriptionMatch.Success) {
        throw "В $sourcePath отсутствует description"
    }

    # temperature из канонического frontmatter не переносится: у agent-файла Vibe
    # нет per-agent температуры (она задаётся в [[models]]).
    $description = $descriptionMatch.Groups['value'].Value.Trim().Trim('"').Trim("'")
    $body = $documentMatch.Groups['body'].Value.Trim()
    if ($body.Contains('"""')) {
        throw "Body $sourcePath содержит TOML multiline delimiter"
    }

    # Томл basic multiline string обрабатывает escape-последовательности: бэкслеши экранируем.
    $escapedBody = $body.Replace('\', '\\')
    if ($escapedBody.Length -gt $maxInstructionsLength) {
        throw "Instructions $sourcePath длиннее $maxInstructionsLength символов"
    }

    $lines = @(
        '# Generated by sync-vibe-agents.ps1. Do not edit manually.'
        'agent_type = "subagent"'
        ('description = "{0}"' -f (ConvertTo-TomlString $description))
        ('disabled_tools = [{0}]' -f (($disabledTools | ForEach-Object { '"{0}"' -f (ConvertTo-TomlString $_) }) -join ', '))
        'instructions = """'
        $escapedBody
        '"""'
    )

    # Read-only роли: канонический permission.edit=deny → запрет файловых правок
    # (bash остаётся у сессии: verifier запускает checks).
    if ($agentName -in $readOnlyAgents) {
        $lines += @(
            ''
            '[tools.write_file]'
            'permission = "never"'
            ''
            '[tools.edit]'
            'permission = "never"'
        )
    }

    $generated = $lines -join "`n"
    Set-Content -LiteralPath (Join-Path $outputRoot "$agentName.toml") -Value $generated -Encoding utf8NoBOM
}

Write-Host "Generated $($agentNames.Count) Vibe agent profiles."
